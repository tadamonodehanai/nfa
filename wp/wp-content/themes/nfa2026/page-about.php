<h3 class="h3j" id="welfare">健全育成クラブガイドラインチェックリスト</h3>
<div class="prose">
<p>NAGANO FA 2020宣言「各種大会やチームにウェルフェアオフィサーを置きます。」</p>
<p>長野県サッカー協会では、誰もが安心・安全にスポーツに参加できる環境をめざし、ウェルフェアオフィサーの配置やリスペクト活動に取り組んでいます。その一環として、育成年代のチームにおいて日々の活動や運営で目指すべき内容をガイドラインとして示し、それを確認するための「健全育成クラブガイドラインチェックリスト」を作成しました。</p>
<p>チェックリストの実施は、Google formでのご回答をお願いします。回答されたクラブについて、希望がある場合は、県協会HPへ「健全育成・暴力根絶への取り組みを行っているクラブ＝健全育成クラブ」として掲出いたします。回答内容については、チームが特定されることのないよう統計処理させていただきます。</p>
