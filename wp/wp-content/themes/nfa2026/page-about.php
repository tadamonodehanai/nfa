<div class="bh"><div><div class="e">ACTION <i>PLAN</i></div><h2>理念・ビジョンの改訂とアクションプラン</h2></div></div>
<div class="plan-v"><span class="e">2020.09 REVISED</span><h3>NFA理念・ビジョンの改訂（2020年9月）</h3><p>2006年に設定され施行されていたNFA理念・ビジョンを改訂しました。</p></div>
<div class="prose ab-msg">
<p>この理念・ビジョンに基づき、サッカーを通じて豊かなスポーツ文化を創造し、長野県のサッカーが全国で活躍できることを目標とした育成に努めます。</p>
<p>また、2020年宣言を通してアクションプランを設定し、2028年長野国民スポーツ大会を含め、10年後を見据えた強化をし、サッカーファミリーの皆さんと共に発展していきたいと思います。</p>
<p class="ab-sign"><span class="ib">2020年10月　</span><span class="ib">（一社）長野県サッカー協会　</span><span class="ib">会長　松田正己</span></p>
