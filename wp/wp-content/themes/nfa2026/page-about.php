<section class="blk pale" id="business"><div class="wrap">
<div class="bh"><div><div class="e">BUSINESS</div><h2>事業内容（定款より）</h2></div></div>
<p class="lead2">一般社団法人 長野県サッカー協会の事業です。</p>
<ol class="ab-biz">
<li>サッカー技術の研究及び指導に関すること。</li>
<li>審判技術の研究及び審判員の養成に関すること。</li>
<li>サッカー競技力向上のための選手の育成強化に関すること。</li>
<li>長野県サッカー<span class="nw">選手権大会</span>その他の競技会の開催に関すること。</li>
<li>指導者の養成及び指導技術の研究に関すること。</li>
<li>本県を代表するチームの役員、選手の選定及び派遣に関すること。</li>
<li>公式競技会及びその他の試合に関し記録を作成し、保存すること。</li>
<li>公益財団法人日本サッカー協会（以下、「日本協会」という。）に加盟登録するチーム、選手、指導者、審判員及び審判指導者の登録申請並びに承認に関すること。</li>
<li>その他、一般社団法人長野県サッカー協会の目的を達成するために必要な事業。</li>
</ol>
</div></section>
