<h2 id="p3"><span class="no">3.</span>クッキー（Cookie）の利用</h2>
<p>当協会は、前記の利用目的のために、クッキー（Cookie）を利用して情報を収集させていただくことがあります。クッキー（Cookie）とは、ウェブ・サーバから送信されてコンピュータのハードディスクドライブにインターネットブラウザにより保存される少量のデータです。</p>
<p>クッキー（Cookie）自体には、利用者のお名前、ご住所、電話番号、電子メールアドレスなど個人を識別する情報は含まれませんが、利用者が個人情報等を当協会に提供されると、利用者が当サイトにアクセスされる際に利用者が使用されるパソコン等の通信端末が特定されます。ただし、クッキー（Cookie）を利用して、利用者のハードディスクドライブのデータや、電子メールアドレス、利用者個人の識別情報を入手することは出来ません。</p>
<p>利用者ご自身で、ブラウザの設定を操作することで、クッキー（Cookies）の受け取りを拒否することも可能です。その場合でも当サイトの閲覧に支障を来すことはありません。なお、ブラウザの設定方法がご不明の場合は各ソフト製造元へお問い合わせ下さい。</p>
